"""Trajectory-level adapter for normalized Nemotron AIQ runtime traces."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from ag_types import Action, GuardrailContext, InteractionHistory, Observation
from evals.base import BaseBenchmarkAdapter, EvalCase


class NemotronAIQAdapter(BaseBenchmarkAdapter):
    """Evaluate final safe/unsafe outcomes from preprocessed AIQ OTel traces.

    Input is JSONL generated by ``prepare_nemotron_aiq_realtrace_benchmark.py``.
    The source attack manifest is intentionally not exposed in ``history`` or
    ``context`` so outcome labels cannot leak into the model prompt.
    """

    name = "nemotron_aiq_traj"

    def __init__(self, input_path: str | Path, *, limit: int | None = None) -> None:
        self.input_path = Path(input_path)
        self.limit = limit

    def _load_rows(self) -> list[dict[str, Any]]:
        if not self.input_path.exists():
            raise FileNotFoundError(f"Nemotron AIQ input does not exist: {self.input_path}")
        rows = [json.loads(line) for line in self.input_path.read_text(encoding="utf-8").splitlines() if line.strip()]
        if self.limit is not None:
            rows = rows[: self.limit]
        return rows

    def _build_case(self, row: dict[str, Any]) -> EvalCase:
        events = row.get("events")
        if not isinstance(events, list) or not events or not all(isinstance(event, dict) for event in events):
            raise ValueError(f"Nemotron AIQ case {row.get('case_id')} requires non-empty event objects")

        history = InteractionHistory(
            user_request=str(row.get("user_request") or "User request unavailable in source trace."),
            initial_state="Runtime trace from an AIQ Research Assistant interaction.",
        )
        tool_names: list[str] = []
        for step, event in enumerate(events[:-1], start=1):
            self._append_event(history, event, step=step, tool_names=tool_names)

        action = self._event_action(events[-1], step=len(events), tool_names=tool_names)
        metadata = dict(row.get("metadata") or {})
        metadata["event_count"] = len(events)
        return EvalCase(
            case_id=str(row["case_id"]),
            history=history,
            action=action,
            context=GuardrailContext(
                available_tools=[{"name": name, "description": "Observed runtime tool."} for name in tool_names] or None,
            ),
            gold_label=int(row["gold_label"]),
            metadata=metadata,
        )

    def load_cases(self) -> list[EvalCase]:
        return [self._build_case(row) for row in self._load_rows()]

    @staticmethod
    def _event_text(event: dict[str, Any]) -> str:
        kind = str(event.get("kind") or "UNKNOWN")
        name = str(event.get("name") or "unknown")
        parts = [f"[{kind}] {name}"]
        if event.get("input"):
            parts.append(f"Input: {event['input']}")
        if event.get("output"):
            parts.append(f"Output: {event['output']}")
        return "\n".join(parts)

    @classmethod
    def _event_action(cls, event: dict[str, Any], *, step: int, tool_names: list[str]) -> Action:
        kind = str(event.get("kind") or "UNKNOWN").upper()
        name = str(event.get("name") or "unknown")
        if kind == "TOOL":
            if name not in tool_names:
                tool_names.append(name)
            return Action(
                tool_name=name,
                arguments={"observed_input": str(event.get("input") or "")},
                raw_text=cls._event_text(event),
                thought="",
                step=step,
            )
        return Action(
            tool_name=None,
            arguments={},
            raw_text=cls._event_text(event),
            thought="",
            step=step,
        )

    @classmethod
    def _append_event(
        cls,
        history: InteractionHistory,
        event: dict[str, Any],
        *,
        step: int,
        tool_names: list[str],
    ) -> None:
        kind = str(event.get("kind") or "UNKNOWN").upper()
        if kind == "TOOL":
            history.add_action(cls._event_action(event, step=step, tool_names=tool_names))
            output = str(event.get("output") or "")
            if output:
                history.add_observation(Observation(content=f"Tool output from {event.get('name')}: {output}", step=step))
            return
        history.add_action(cls._event_action(event, step=step, tool_names=tool_names))
